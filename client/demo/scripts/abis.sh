#!/usr/bin/env bash
# Writes the contract ABIs the web app imports, from Foundry's build output.
set -euo pipefail
cd "$(dirname "$0")/../../../contracts/brake"
forge build >/dev/null
out=../../client/demo/src/chains/evm/abis.ts
{
  echo "// Generated by client/demo/scripts/abis.sh from Foundry's out/. Do not edit."
  for c in Brake DemoAccount DemoDollar DemoWorld; do
    name="$(echo "${c:0:1}" | tr A-Z a-z)${c:1}Abi"
    echo "export const $name = $(jq -c '.abi' out/$c.sol/$c.json) as const"
  done
} > $out
